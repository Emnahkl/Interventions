-- Fire Station — modèle physique commun (compatible Oracle XE 11g R2 / 11.2)
-- Exécuter dans le schéma Oracle de l'étudiant, après création de la connexion.
-- Les noms sont conservés en majuscules pour correspondre aux noms Oracle non quotés.

CREATE TABLE CENTRE (
    ID_CENTRE NUMBER PRIMARY KEY,
    NOM VARCHAR2(120) NOT NULL,
    ADRESSE VARCHAR2(250),
    TELEPHONE VARCHAR2(30),
    CONSTRAINT UQ_CENTRE_NOM UNIQUE (NOM)
);

CREATE TABLE ZONE_COUVERTURE (
    ID_ZONE NUMBER PRIMARY KEY,
    ID_CENTRE NUMBER NOT NULL,
    NOM VARCHAR2(120) NOT NULL,
    REGION_QUARTIER VARCHAR2(160),
    SUPERFICIE_KM2 NUMBER(10,2),
    POPULATION_ESTIMEE NUMBER(12),
    NIVEAU_RISQUE VARCHAR2(20) NOT NULL,
    TEMPS_MOYEN_REPONSE_MIN NUMBER(8,2),
    CONSTRAINT FK_ZONE_CENTRE FOREIGN KEY (ID_CENTRE) REFERENCES CENTRE(ID_CENTRE),
    CONSTRAINT CK_ZONE_RISQUE CHECK (NIVEAU_RISQUE IN ('Faible','Moyen','Élevé','Critique')),
    CONSTRAINT CK_ZONE_POP CHECK (POPULATION_ESTIMEE IS NULL OR POPULATION_ESTIMEE >= 0)
);

CREATE TABLE EMPLOYE (
    ID_EMPLOYE NUMBER PRIMARY KEY,
    ID_CENTRE NUMBER NOT NULL,
    NOM VARCHAR2(80) NOT NULL,
    PRENOM VARCHAR2(80) NOT NULL,
    GRADE VARCHAR2(80),
    SPECIALITE VARCHAR2(100),
    TELEPHONE VARCHAR2(30),
    EMAIL VARCHAR2(160) NOT NULL,
    MOT_DE_PASSE_HASH VARCHAR2(255) NOT NULL,
    ACTIF CHAR(1) DEFAULT 'O' NOT NULL,
    CONSTRAINT FK_EMPLOYE_CENTRE FOREIGN KEY (ID_CENTRE) REFERENCES CENTRE(ID_CENTRE),
    CONSTRAINT UQ_EMPLOYE_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_EMPLOYE_ACTIF CHECK (ACTIF IN ('O','N'))
);

CREATE TABLE VEHICULE (
    ID_VEHICULE NUMBER PRIMARY KEY,
    ID_CENTRE NUMBER NOT NULL,
    ID_ZONE NUMBER,
    IMMATRICULATION VARCHAR2(20) NOT NULL,
    TYPE_VEHICULE VARCHAR2(80) NOT NULL,
    MODELE VARCHAR2(120),
    ETAT VARCHAR2(30) DEFAULT 'Disponible' NOT NULL,
    KILOMETRAGE NUMBER(12) DEFAULT 0 NOT NULL,
    DATE_MISE_EN_SERVICE DATE,
    DATE_DERNIERE_MAINTENANCE DATE,
    DATE_PROCHAINE_MAINTENANCE DATE,
    KM_PROCHAINE_MAINTENANCE NUMBER(12),
    NOTES VARCHAR2(1000),
    CONSTRAINT UQ_VEHICULE_IMMAT UNIQUE (IMMATRICULATION),
    CONSTRAINT FK_VEHICULE_CENTRE FOREIGN KEY (ID_CENTRE) REFERENCES CENTRE(ID_CENTRE),
    CONSTRAINT FK_VEHICULE_ZONE FOREIGN KEY (ID_ZONE) REFERENCES ZONE_COUVERTURE(ID_ZONE),
    CONSTRAINT CK_VEHICULE_ETAT CHECK (ETAT IN ('Disponible','En intervention','En maintenance','Hors service')),
    CONSTRAINT CK_VEHICULE_KM CHECK (KILOMETRAGE >= 0)
);

CREATE TABLE MAINTENANCE (
    ID_MAINTENANCE NUMBER PRIMARY KEY,
    ID_VEHICULE NUMBER NOT NULL,
    ID_EMPLOYE_RESPONSABLE NUMBER,
    DATE_MAINTENANCE DATE NOT NULL,
    TYPE_MAINTENANCE VARCHAR2(80) NOT NULL,
    KILOMETRAGE NUMBER(12),
    DESCRIPTION VARCHAR2(1000),
    COUT NUMBER(12,2),
    PROCHAINE_ECHEANCE DATE,
    CONSTRAINT FK_MAINT_VEHICULE FOREIGN KEY (ID_VEHICULE) REFERENCES VEHICULE(ID_VEHICULE),
    CONSTRAINT FK_MAINT_EMPLOYE FOREIGN KEY (ID_EMPLOYE_RESPONSABLE) REFERENCES EMPLOYE(ID_EMPLOYE),
    CONSTRAINT CK_MAINT_COUT CHECK (COUT IS NULL OR COUT >= 0)
);

CREATE TABLE EQUIPEMENT (
    ID NUMBER PRIMARY KEY,
    NOM VARCHAR2(160) NOT NULL,
    TYPE_EQUIP VARCHAR2(100),
    QUANTITE NUMBER(10) DEFAULT 0 NOT NULL,
    DATE_ACQUISITION DATE,
    ETAT VARCHAR2(40),
    DATE_CONTROLE DATE,
    AFFECTATION VARCHAR2(200),
    SEUIL_ALERTE NUMBER(10) DEFAULT 5,
    ID_CENTRE NUMBER,
    DATE_EXPIRATION DATE,
    CONSTRAINT FK_EQUIPEMENT_CENTRE FOREIGN KEY (ID_CENTRE) REFERENCES CENTRE(ID_CENTRE),
    CONSTRAINT CK_EQUIPEMENT_QTE CHECK (QUANTITE >= 0),
    CONSTRAINT CK_EQUIPEMENT_SEUIL CHECK (SEUIL_ALERTE IS NULL OR SEUIL_ALERTE >= 0)
);

CREATE TABLE VEHICULE_EQUIPEMENT (
    ID_VEHICULE NUMBER NOT NULL,
    ID_EQUIPEMENT NUMBER NOT NULL,
    QUANTITE_AFFECTEE NUMBER(8) DEFAULT 1 NOT NULL,
    DATE_AFFECTATION DATE DEFAULT SYSDATE NOT NULL,
    DATE_RETRAIT DATE,
    CONSTRAINT PK_VEHICULE_EQUIPEMENT PRIMARY KEY (ID_VEHICULE, ID_EQUIPEMENT, DATE_AFFECTATION),
    CONSTRAINT FK_VE_VEHICULE FOREIGN KEY (ID_VEHICULE) REFERENCES VEHICULE(ID_VEHICULE),
    CONSTRAINT FK_VE_EQUIPEMENT FOREIGN KEY (ID_EQUIPEMENT) REFERENCES EQUIPEMENT(ID),
    CONSTRAINT CK_VE_QTE CHECK (QUANTITE_AFFECTEE > 0)
);

CREATE TABLE INTERVENTION (
    ID_INTERVENTION NUMBER PRIMARY KEY,
    ID_ZONE NUMBER NOT NULL,
    TYPE_INTERVENTION VARCHAR2(100) NOT NULL,
    ADRESSE VARCHAR2(250) NOT NULL,
    DATE_HEURE DATE DEFAULT SYSDATE NOT NULL,
    PRIORITE VARCHAR2(20) DEFAULT 'Normale' NOT NULL,
    STATUT VARCHAR2(30) DEFAULT 'Planifiée' NOT NULL,
    DESCRIPTION VARCHAR2(1500),
    LATITUDE NUMBER(10,7),
    LONGITUDE NUMBER(10,7),
    CONSTRAINT FK_INTERVENTION_ZONE FOREIGN KEY (ID_ZONE) REFERENCES ZONE_COUVERTURE(ID_ZONE),
    CONSTRAINT CK_INTERV_PRIORITE CHECK (PRIORITE IN ('Basse','Normale','Haute','Urgente')),
    CONSTRAINT CK_INTERV_STATUT CHECK (STATUT IN ('Planifiée','En cours','Terminée','Annulée'))
);

CREATE TABLE INTERVENTION_EMPLOYE (
    ID_INTERVENTION NUMBER NOT NULL,
    ID_EMPLOYE NUMBER NOT NULL,
    ROLE_INTERVENTION VARCHAR2(80),
    CONSTRAINT PK_INTERVENTION_EMPLOYE PRIMARY KEY (ID_INTERVENTION, ID_EMPLOYE),
    CONSTRAINT FK_IE_INTERVENTION FOREIGN KEY (ID_INTERVENTION) REFERENCES INTERVENTION(ID_INTERVENTION),
    CONSTRAINT FK_IE_EMPLOYE FOREIGN KEY (ID_EMPLOYE) REFERENCES EMPLOYE(ID_EMPLOYE)
);

CREATE TABLE INTERVENTION_VEHICULE (
    ID_INTERVENTION NUMBER NOT NULL,
    ID_VEHICULE NUMBER NOT NULL,
    CONSTRAINT PK_INTERVENTION_VEHICULE PRIMARY KEY (ID_INTERVENTION, ID_VEHICULE),
    CONSTRAINT FK_IV_INTERVENTION FOREIGN KEY (ID_INTERVENTION) REFERENCES INTERVENTION(ID_INTERVENTION),
    CONSTRAINT FK_IV_VEHICULE FOREIGN KEY (ID_VEHICULE) REFERENCES VEHICULE(ID_VEHICULE)
);

CREATE TABLE CAMPAGNE (
    ID_CAMPAGNE NUMBER PRIMARY KEY,
    ID_CENTRE NUMBER NOT NULL,
    ID_ZONE NUMBER,
    TITRE VARCHAR2(160) NOT NULL,
    THEME VARCHAR2(120) NOT NULL,
    DATE_CAMPAGNE DATE NOT NULL,
    LIEU VARCHAR2(250),
    PUBLIC_CIBLE VARCHAR2(200),
    NB_PARTICIPANTS NUMBER(10) DEFAULT 0 NOT NULL,
    IMPACT_OBSERVE VARCHAR2(1000),
    CONSTRAINT FK_CAMPAGNE_CENTRE FOREIGN KEY (ID_CENTRE) REFERENCES CENTRE(ID_CENTRE),
    CONSTRAINT FK_CAMPAGNE_ZONE FOREIGN KEY (ID_ZONE) REFERENCES ZONE_COUVERTURE(ID_ZONE),
    CONSTRAINT CK_CAMPAGNE_PART CHECK (NB_PARTICIPANTS >= 0)
);

CREATE TABLE PARTICIPATION_CAMPAGNE (
    ID_CAMPAGNE NUMBER NOT NULL,
    ID_EMPLOYE NUMBER NOT NULL,
    ROLE_PARTICIPATION VARCHAR2(80),
    CONSTRAINT PK_PARTICIPATION_CAMPAGNE PRIMARY KEY (ID_CAMPAGNE, ID_EMPLOYE),
    CONSTRAINT FK_PC_CAMPAGNE FOREIGN KEY (ID_CAMPAGNE) REFERENCES CAMPAGNE(ID_CAMPAGNE),
    CONSTRAINT FK_PC_EMPLOYE FOREIGN KEY (ID_EMPLOYE) REFERENCES EMPLOYE(ID_EMPLOYE)
);

CREATE TABLE PLANNING_EMPLOYE (
    ID_PLANNING NUMBER PRIMARY KEY,
    ID_EMPLOYE NUMBER NOT NULL,
    DATE_DEBUT DATE NOT NULL,
    DATE_FIN DATE NOT NULL,
    TYPE_SERVICE VARCHAR2(80),
    NOTES VARCHAR2(500),
    CONSTRAINT FK_PLANNING_EMPLOYE FOREIGN KEY (ID_EMPLOYE) REFERENCES EMPLOYE(ID_EMPLOYE),
    CONSTRAINT CK_PLANNING_DATES CHECK (DATE_FIN >= DATE_DEBUT)
);

-- Oracle 11g n'a pas de colonnes IDENTITY : séquences et triggers génèrent les clés.
CREATE SEQUENCE SEQ_CENTRE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_ZONE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_EMPLOYE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_VEHICULE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_MAINTENANCE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_EQUIPEMENT START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_INTERVENTION START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_CAMPAGNE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PLANNING START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER TRG_CENTRE_BI BEFORE INSERT ON CENTRE FOR EACH ROW
WHEN (NEW.ID_CENTRE IS NULL)
BEGIN SELECT SEQ_CENTRE.NEXTVAL INTO :NEW.ID_CENTRE FROM DUAL; END;
/
CREATE OR REPLACE TRIGGER TRG_ZONE_BI BEFORE INSERT ON ZONE_COUVERTURE FOR EACH ROW
WHEN (NEW.ID_ZONE IS NULL)
