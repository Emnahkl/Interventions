WHEN (NEW.ID_PLANNING IS NULL)
BEGIN SELECT SEQ_PLANNING.NEXTVAL INTO :NEW.ID_PLANNING FROM DUAL; END;
/

CREATE INDEX IX_VEHICULE_CENTRE_ETAT ON VEHICULE(ID_CENTRE, ETAT);
CREATE INDEX IX_VEHICULE_MAINTENANCE ON VEHICULE(DATE_PROCHAINE_MAINTENANCE, KM_PROCHAINE_MAINTENANCE);
CREATE INDEX IX_EQUIPEMENT_ALERTE ON EQUIPEMENT(QUANTITE, SEUIL_ALERTE);
CREATE INDEX IX_INTERVENTION_DATE ON INTERVENTION(DATE_HEURE, STATUT);
CREATE INDEX IX_ZONE_RISQUE ON ZONE_COUVERTURE(NIVEAU_RISQUE);
